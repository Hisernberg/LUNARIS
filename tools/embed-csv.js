#!/usr/bin/env node
// Regenerates data/embedded.js - verbatim copies of every CSV, so the game works from
// file:// where fetch() is blocked. Run after editing any dataset:  node tools/embed-csv.js
const fs = require('fs');
const path = require('path');

const DATA = path.join(__dirname, '..', 'data');
const files = fs.readdirSync(DATA).filter(f => f.endsWith('.csv')).sort();
const out = [];
out.push('// AUTO-GENERATED by tools/embed-csv.js - do not edit by hand.');
out.push('// Verbatim copies of the CSVs in data/ for file:// fallback.');
out.push('window.LUNARIS_EMBEDDED = {');
for (const f of files) {
  const text = fs.readFileSync(path.join(DATA, f), 'utf8').replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  out.push(`  ${JSON.stringify(f)}: \`\n${text}\`,`);
}
out.push('};');
fs.writeFileSync(path.join(DATA, 'embedded.js'), out.join('\n') + '\n');
console.log(`embedded.js written: ${files.length} datasets, ${(fs.statSync(path.join(DATA, 'embedded.js')).size / 1024).toFixed(1)} KB`);
